/**
 * Strategy Prospects (QUESTION-2026-11-09 (i)): non-dated enquiries. Admin only (x-arp-admin-key) for reads and writes,
 * because rows hold personal data. Nothing is emailed to anyone from here; no £ is added to actual sales.
 * GET  → { rows, config, history, clients } for the Strategy table (admin key).
 * POST { action: 'upsert', via: 'gpt' | 'claude', enquiry: { id?, enquiry_date (received, required on create), client_or_org,
 *        client_email?, person_id?, type, value_gbp, value_basis, value_basis_note, customer_market, review_status,
 *        stage, cash_month, next_action, next_action_date, owner, last_touch_at, source, source_ref, lost_reason, notes },
 *        matched_sale? }
 *   - enquiry_ref (ENQ-0001 …) is generated by the database and returned;
 *   - client ID: person_id if given (must exist); else match customer_person by client_email (exact), then by an exact
 *     name naming exactly one contact with an email; else create a "prospect" customer_person with no consent fields
 *     (no subscription, no suppression, no audience membership). The method is logged in history;
 *   - idempotent by id, or by source_ref (the Gmail message id) + client: an unchanged payload writes nothing;
 *   - value_gbp is the full order value; a new enquiry with a value needs value_basis (agreed / quoted / estimated /
 *     unknown); customer_market D2C / B2B / unclassified; review_status recent / revalidate (never closed by age);
 *   - every create / change appends a history row (stage from → to, changed fields, who, via, when);
 *   - stage booked_paid needs matched_sale { txn_date, amount } (or { source_workbook, source_row }): only a Booking
 *     Sheet sale linked to the SAME client is matched; another client's sale is refused; several possible sales (or one
 *     not linked yet) leave it unmatched and flagged for review (history changes.match_review);
 *   - stage closed_lost needs lost_reason.
 *   - revenue_type (QUESTION-2026-11-09 (r)): new_sale (default) / partner_development / committed_work / receivable, with
 *     delivery_due + invoice_by (committed work). Stage "allocated" (Allocated · delivery pending) is committed work only
 *     and is the default for it; a receivable defaults to "scheduled". A receivable is paid (booked_paid) only on a
 *     same-client Booking Sheet matched_sale or paid_evidence { provider: paypal | stripe | squarespace | bank, ref } —
 *     never on the buyer's word; committed work only on a Booking Sheet matched_sale (never automatically).
 *   - relates_to_event (QUESTION-2026-11-09 (v)): "YYYY-MM-DD|/event-page-path" (or the full page URL after the |) for an
 *     enquiry about a dated event; blank clears it. GET also returns revalidate_factor (old "revalidate" leads × 0.25).
 *   - Gmail links (QUESTION-2026-11-09 (x)), GET only: clients[person_id].mail = all mail to / from the linked
 *     customer_person's email (or the quoted name: "no email on file"); rows[].mail = the original enquiry email
 *     (source_ref). The email is read server-side here and never appears in the public strategy summary.
 *   - QUESTION-2026-11-09 (z / bb): an update may name the row by id OR enquiry_ref (an unknown enquiry_ref is refused);
 *     the row is found (id / enquiry_ref, else source_ref + client) BEFORE validation and nothing is written until it
 *     passes; committed work: allocated / delivered / invoiced (committed only); closed_lost needs lost_reason (a code:
 *     not_interested / no_response / went_elsewhere / too_expensive / not_a_fit / duplicate / other — other needs
 *     status_note); parked needs revisit_on. A refused change returns { error, field, reason } for the form.
 *   - GET rows carry priority { band, score, tip } (new sales at open stages) and flags.parked_due.
 * The same rules for Claude's loads through Supabase SQL: public.prospect_upsert(p jsonb) (migrations/prospect_upsert_function_20261109.sql).
 */

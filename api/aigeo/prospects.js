/**
 * Strategy Prospects (QUESTION-2026-11-09 (i)): non-dated enquiries. Admin only (x-arp-admin-key) for reads and writes,
 * because rows hold personal data. Nothing is emailed to anyone from here; no £ is added to actual sales.
 * GET  → { rows, config, history, clients } for the Strategy table (admin key).
 * POST { action: 'upsert', via: 'gpt' | 'claude', enquiry: { id?, enquiry_date (received, required on create), client_or_org,
 *        client_email?, person_id?, type, value_gbp, value_basis, value_basis_note, customer_market, review_status,
 *        stage, cash_month, next_action, next_action_date, owner, last_touch_at, source, source_ref, lost_reason, notes },
 *        matched_sale? }
 *   - enquiry_ref (ENQ-0001 …) is generated by the database and returned;
 *   - client ID: person_id if given (must exist); else match customer_person by client_email (exact), then by an exact
 *     name naming exactly one contact with an email; else create a "prospect" customer_person with no consent fields
 *     (no subscription, no suppression, no audience membership). The method is logged in history;
 *   - idempotent by id, or by source_ref (the Gmail message id) + client: an unchanged payload writes nothing;
 *   - value_gbp is the full order value; a new enquiry with a value needs value_basis (agreed / quoted / estimated /
 *     unknown); customer_market D2C / B2B / unclassified; review_status recent / revalidate (never closed by age);
 *   - every create / change appends a history row (stage from → to, changed fields, who, via, when);
 *   - stage booked_paid needs matched_sale { txn_date, amount } (or { source_workbook, source_row }): only a Booking
 *     Sheet sale linked to the SAME client is matched; another client's sale is refused; several possible sales (or one
 *     not linked yet) leave it unmatched and flagged for review (history changes.match_review);
 *   - stage closed_lost needs lost_reason.
 *   - revenue_type (QUESTION-2026-11-09 (r)): new_sale (default) / partner_development / committed_work / receivable, with
 *     delivery_due + invoice_by (committed work). Stage "allocated" (Allocated · delivery pending) is committed work only
 *     and is the default for it; a receivable defaults to "scheduled". A receivable is paid (booked_paid) only on a
 *     same-client Booking Sheet matched_sale or paid_evidence { provider: paypal | stripe | squarespace | bank, ref } —
 *     never on the buyer's word; committed work only on a Booking Sheet matched_sale (never automatically).
 * The same rules for Claude's loads through Supabase SQL: public.prospect_upsert(p jsonb) (migrations/prospect_upsert_function_20261109.sql).
 */
import { createClient } from '@supabase/supabase-js';
import { requireAdminKeyOnly } from '../../lib/api/requireAdminKeyOnly.js';
import { randomUUID } from 'node:crypto';
import { DEFAULT_STAGE, MARKETS, OWNERS, PROVIDERS, REVENUE_TYPES, REVIEW, SOURCES, STAGES, TYPES, VALUE_BASES, pickClient, pickSale, prospectPersonRow, rowFlags, shortClientId } from '../../lib/strategy-prospects.mjs';

const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;
const MONTH_RE = /^(\d{4}-\d{2})(-\d{2})?$/;
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const ID_RE = /^[A-Za-z0-9._:-]{3,80}$/;

function send(res, status, body) {
  res.setHeader('Content-Type', 'application/json; charset=utf-8');
  res.setHeader('Cache-Control', 'no-store');
  res.status(status).send(JSON.stringify(body));
}
function client() {
  return createClient(process.env.SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY, { auth: { persistSession: false } });
}
const BY = { claude: 'Alan via Claude (admin key)', gpt: 'Alan via GPT (admin key)', cursor: 'Cursor self-test (admin key)' };
export const setByOf = (b) => BY[b?.via] || 'Alan (dashboard, admin key)';
export const viaOf = (b) => (BY[b?.via] ? b.via : 'dashboard');

/* ---------- validation ---------- */

const text = (max) => (v) => (v == null || String(v).trim() === '' ? null : String(v).trim().slice(0, max));
const oneOf = (list, name) => (v) => {
  if (!list.includes(v)) throw new Error(`${name} must be one of: ${list.join(', ')}`);
  return v;
};
const oneOfOrNull = (list, name) => (v) => (v == null || v === '' ? null : oneOf(list, name)(v));
function date(v) {
  if (v == null || v === '') return null;
  if (!DATE_RE.test(String(v))) throw new Error('dates must be YYYY-MM-DD');
  return String(v);
}
function cashMonth(v) {
  if (v == null || v === '') return null;
  const m = MONTH_RE.exec(String(v));
  if (!m) throw new Error('cash_month must be YYYY-MM (or a date in that month)');
  return `${m[1]}-01`;
}
function money(v) {
  const n = Number(v);
  if (!Number.isFinite(n) || n < 0 || n > 1e6) throw new Error('value_gbp must be a number of pounds ≥ 0');
  return Math.round(n * 100) / 100;
}
function stamp(v) {
  if (v == null || v === '') return null;
  const t = Date.parse(String(v));
  if (!Number.isFinite(t)) throw new Error('last_touch_at must be a date or ISO time');
  return new Date(t).toISOString();
}
function uuid(v) {
  if (v == null || v === '') return null;
  if (!UUID_RE.test(String(v))) throw new Error('person_id must be a customer_person uuid');
  return String(v);
}
function received(v) {
  const d = date(v);
  if (d && d > new Date(Date.now() + 864e5).toISOString().slice(0, 10)) throw new Error('enquiry_date cannot be in the future');
  return d;
}
const FIELDS = {
  enquiry_date: received, client_or_org: text(200), person_id: uuid, type: oneOf(TYPES, 'type'), value_gbp: money, stage: oneOf(STAGES, 'stage'), cash_month: cashMonth,
  next_action: text(300), next_action_date: date, owner: oneOf(OWNERS, 'owner'), last_touch_at: stamp, source: oneOfOrNull(SOURCES, 'source'),
  lost_reason: text(300), notes: text(500), customer_market: oneOf(MARKETS, 'customer_market'), value_basis: oneOf(VALUE_BASES, 'value_basis'),
  value_basis_note: text(500), review_status: oneOf(REVIEW, 'review_status'), source_ref: text(200),
  revenue_type: oneOf(REVENUE_TYPES, 'revenue_type'), delivery_due: date, invoice_by: date
};
/** Only the fields sent are validated and written. */
export function enquiryPatch(e) {
  const patch = {};
  for (const [f, fn] of Object.entries(FIELDS)) if (e?.[f] !== undefined) patch[f] = fn(e[f]);
  if (patch.client_or_org === null) throw new Error('client_or_org cannot be empty');
  return patch;
}
export function idOf(v) {
  if (v == null || v === '') return null;
  if (!ID_RE.test(String(v))) throw new Error('id: 3–80 letters, digits, . _ : -');
  return String(v);
}
const same = (a, b) => (a == null && b == null) || String(a) === String(b) || (Number.isFinite(Number(a)) && Number(a) === Number(b) && a !== '' && b !== '');
const DATE_COLS = new Set(['cash_month', 'next_action_date', 'delivery_due', 'invoice_by']);
export function changesOf(prev, patch) {
  const out = {};
  for (const [k, v] of Object.entries(patch)) {
    const was = DATE_COLS.has(k) ? (prev?.[k] ? String(prev[k]).slice(0, 10) : null) : prev?.[k] ?? null;
    if (!same(was, v)) out[k] = { from: was, to: v };
  }
  return out;
}
/** A new enquiry needs who, what and the date it was received; the received date can never be cleared. */
function requiredFields(prev, patch) {
  if (prev) {
    if (patch.enquiry_date === null) throw new Error('enquiry_date cannot be cleared');
    return;
  }
  if (!patch.client_or_org || !patch.type) throw new Error('a new enquiry needs client_or_org and type');
  if (!patch.enquiry_date) throw new Error('a new enquiry needs enquiry_date (the date it was received, YYYY-MM-DD)');
  if (!patch.value_basis && Number(patch.value_gbp) > 0) throw new Error('a new enquiry with a value needs value_basis (agreed / quoted / estimated / unknown)');
}
/** Stage rules: booked_paid needs a Booking Sheet match; closed_lost needs a reason; a new row needs who and what. */
/** The row's revenue type and stage after this patch (a new row starts at its type's default stage). */
function typeAndStage(prev, patch) {
  const type = patch.revenue_type || prev?.revenue_type || 'new_sale';
  return { type, stage: patch.stage || prev?.stage || DEFAULT_STAGE[type] };
}
export function stageRule(prev, patch, matched) {
  const { type, stage } = typeAndStage(prev, patch);
  requiredFields(prev, patch);
  if (stage === 'allocated' && type !== 'committed_work') throw new Error('stage allocated (Allocated · delivery pending) is for revenue_type committed_work only');
  if (stage === 'booked_paid' && prev?.stage !== 'booked_paid' && !matched) throw new Error('booked_paid needs matched_sale { txn_date, amount } from the Booking Sheet');
  if (stage === 'closed_lost' && !(patch.lost_reason || prev?.lost_reason)) throw new Error('closed_lost needs lost_reason');
  return stage;
}

/* ---------- reads / writes ---------- */

const one = async (q) => {
  const { data, error } = await q;
  if (error) throw new Error(error.message);
  return (data || [])[0] || null;
};
const many = async (q, what) => {
  const { data, error } = await q;
  if (error) throw new Error(`${what}: ${error.message}`);
  return data || [];
};
/**
 * The Booking Sheet sale a booked_paid enquiry is matched to (no client name is copied): every candidate row is read
 * (never the first), then only a sale linked to the SAME person is matched (lib/strategy-prospects.mjs pickSale).
 * Returns {} (no matched_sale sent), { sale } or { review }; another client's sale throws.
 */
async function matchSale(sb, m, personId) {
  if (!m) return {};
  let q = sb.from('booking_sheet_transactions').select('source_workbook, source_row, txn_date, amount, category_label').limit(25);
  if (m.source_workbook && m.source_row != null) q = q.eq('source_workbook', String(m.source_workbook)).eq('source_row', Number(m.source_row));
  else if (DATE_RE.test(String(m.txn_date || '')) && Number.isFinite(Number(m.amount))) q = q.eq('txn_date', m.txn_date).eq('amount', Number(m.amount));
  else throw new Error('matched_sale needs { txn_date, amount } or { source_workbook, source_row }');
  const sales = await many(q, 'Booking Sheet');
  const ids = sales.map((s) => `${s.source_workbook}:${s.source_row}`);
  const links = ids.length ? await many(sb.from('customer_identity_link').select('source_id, person_id, confirmed').eq('source', 'bs_transaction').in('source_id', ids), 'sale links') : [];
  const pick = pickSale(sales, links, personId);
  if (pick.refused) throw new Error(`matched_sale refused: ${pick.refused}`);
  return pick;
}
/* ---------- client ID: match an existing customer_person, else create a "prospect" record (no consent change) ---------- */

const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
export function clientEmail(v) {
  if (v == null || v === '') return null;
  if (!EMAIL_RE.test(String(v).trim())) throw new Error('client_email must be an email address');
  return String(v).trim().toLowerCase();
}
const likeExact = (s) => String(s).replace(/[\\%_]/g, (c) => `\\${c}`);
async function candidates(sb, email, name) {
  const cols = 'person_id, display_name, email';
  const byEmail = email ? (await sb.from('customer_person').select(cols).eq('email', email).limit(5)).data || [] : [];
  const byName = name ? (await sb.from('customer_person').select(cols).ilike('display_name', likeExact(String(name).trim())).limit(10)).data || [] : [];
  return { byEmail, byName };
}
async function createProspectPerson(sb, name, email, now) {
  const row = prospectPersonRow({ name, email, now, uid: randomUUID() });
  const existing = await one(sb.from('customer_person').select('person_id').eq('anchor_key', row.anchor_key));
  if (existing) return existing.person_id;
  const { data, error } = await sb.from('customer_person').insert(row).select('person_id').single();
  if (error) throw new Error(`client record: ${error.message}`);
  return data.person_id;
}
/** The enquiry's client ID: given (validated), kept, matched (email, then exact unique name) or a new prospect record. */
async function resolveClient(sb, e, patch, prev, now) {
  if (patch.person_id) {
    if (!(await one(sb.from('customer_person').select('person_id').eq('person_id', patch.person_id)))) throw new Error('person_id not found in customer_person');
    return { person_id: patch.person_id, method: 'given' };
  }
  const email = clientEmail(e.client_email);
  if (prev?.person_id && !email) return null;
  const name = patch.client_or_org || prev?.client_or_org;
  const hit = pickClient({ ...(await candidates(sb, email, name)), name });
  if (hit.person_id) return { person_id: hit.person_id, method: hit.method };
  return { person_id: await createProspectPerson(sb, name, email, now), method: hit.method === 'name_multiple' ? `created_prospect (name matched ${hit.candidates} contacts)` : 'created_prospect' };
}
async function writeHistory(sb, row) {
  const { error } = await sb.from('prospect_enquiry_history').insert(row);
  if (error) throw new Error(`history: ${error.message}`);
}
/** A receivable's payment seen at the provider (transaction id required): never the buyer's word alone. */
export function providerEvidence(p, revenueType) {
  if (revenueType !== 'receivable') throw new Error('paid_evidence is for receivables only; other types need a Booking Sheet matched_sale');
  if (!PROVIDERS.includes(p?.provider) || !ID_RE.test(String(p?.ref ?? ''))) throw new Error(`paid_evidence needs { provider: ${PROVIDERS.join(' | ')}, ref: the provider transaction id }`);
  return { evidence: 'provider', provider: p.provider, ref: String(p.ref) };
}
/** What lets a row become booked_paid: a matched sale; a review flag only for new sales (receivables / committed work need evidence). */
export const proofOf = (sale, revenueType) => sale.sale || (['receivable', 'committed_work'].includes(revenueType) ? null : sale.review) || null;
/** De-duplication for loads: the same source message (source_ref) for the same client is the same enquiry. */
async function bySourceRef(sb, patch) {
  if (!patch.source_ref || !patch.person_id) return null;
  return one(sb.from('prospect_enquiry').select('*').eq('source_ref', patch.source_ref).eq('person_id', patch.person_id));
}
async function upsertEnquiry(sb, b, now, by) {
  const e = b.enquiry || {};
  const id = idOf(e.id);
  const patch = enquiryPatch(e);
  const byId = id ? await one(sb.from('prospect_enquiry').select('*').eq('id', id)) : null;
  stageRule(byId, patch, b.matched_sale || b.paid_evidence);
  const client = await resolveClient(sb, e, patch, byId, now);
  if (client) patch.person_id = client.person_id;
  const prev = byId || (await bySourceRef(sb, patch));
  const sale = b.paid_evidence ? { sale: providerEvidence(b.paid_evidence, patch.revenue_type || prev?.revenue_type) } : await matchSale(sb, b.matched_sale, patch.person_id || prev?.person_id);
  const ctx = { patch, sale, stage: stageRule(prev, patch, proofOf(sale, patch.revenue_type || prev?.revenue_type)), now, by, via: viaOf(b), client };
  return prev ? updateEnquiry(sb, prev, ctx) : createEnquiry(sb, id, ctx);
}
const reviewOut = (sale) => (sale.review ? { sale_review: sale.review } : {});
async function updateEnquiry(sb, prev, { patch, sale, stage, now, by, via }) {
  const changes = { ...changesOf(prev, patch), ...(sale.review ? { match_review: sale.review } : {}) };
  if (!Object.keys(changes).length && !sale.sale) return { id: prev.id, enquiry_ref: prev.enquiry_ref, unchanged: true };
  const { error } = await sb.from('prospect_enquiry').update({ ...patch, updated_at: now }).eq('id', prev.id);
  if (error) throw new Error(error.message);
  await writeHistory(sb, { enquiry_id: prev.id, at: now, by, via, from_stage: prev.stage, to_stage: stage, changes, matched_sale: sale.sale || null });
  return { id: prev.id, enquiry_ref: prev.enquiry_ref, updated: true, changes, stage, ...reviewOut(sale) };
}
async function createEnquiry(sb, id, { patch, sale, stage, now, by, via, client }) {
  const row = { ...(id ? { id } : {}), stage, owner: 'Alan', ...patch, last_touch_at: patch.last_touch_at || now, created_by: by, created_at: now, updated_at: now };
  const { data, error } = await sb.from('prospect_enquiry').insert(row).select('id, enquiry_ref').single();
  if (error) throw new Error(error.message);
  const changes = { created: true, client: client?.method || null, ...(sale.review ? { match_review: sale.review } : {}) };
  await writeHistory(sb, { enquiry_id: data.id, at: now, by, via, from_stage: null, to_stage: stage, changes, matched_sale: sale.sale || null });
  return { id: data.id, enquiry_ref: data.enquiry_ref, created: true, stage, client: { id: shortClientId(row.person_id), method: client?.method || null }, ...reviewOut(sale) };
}
/** Client ID column: short id + record type for each enquiry's person (admin GET only). */
async function clientsOf(sb, rows) {
  const ids = [...new Set(rows.map((r) => r.person_id).filter(Boolean))];
  if (!ids.length) return {};
  const { data } = await sb.from('customer_person').select('person_id, display_name, record_type:facts->>record_type').in('person_id', ids);
  return Object.fromEntries((data || []).map((p) => [p.person_id, { id: shortClientId(p.person_id), name: p.display_name, record_type: p.record_type || 'person' }]));
}
async function getAll(sb) {
  const [rows, config, history] = await Promise.all([
    sb.from('prospect_enquiry').select('*').order('created_at', { ascending: true }).limit(2000),
    sb.from('prospect_stage_config').select('stage, probability, label, sort').order('sort', { ascending: true }),
    sb.from('prospect_enquiry_history').select('enquiry_id, at, by, via, from_stage, to_stage, changes, matched_sale').order('at', { ascending: true }).limit(10000)
  ]);
  for (const r of [rows, config, history]) if (r.error) throw new Error(r.error.message);
  const today = new Date().toLocaleDateString('en-CA', { timeZone: 'Europe/London' });
  const list = (rows.data || []).map((r) => ({ ...r, flags: rowFlags(r, today) }));
  return { rows: list, config: config.data || [], history: history.data || [], clients: await clientsOf(sb, list) };
}

export default async function handler(req, res) {
  if (req.method === 'OPTIONS') return send(res, 204, {});
  if (!['GET', 'POST'].includes(req.method)) return send(res, 405, { ok: false, error: 'Method not allowed' });
  if (!requireAdminKeyOnly(req, res, send)) return undefined;
  try {
    if (req.method === 'GET') return send(res, 200, { ok: true, ...(await getAll(client())) });
    const b = req.body || {};
    if (b.action !== 'upsert') return send(res, 400, { ok: false, error: "action must be 'upsert'" });
    const by = setByOf(b);
    return send(res, 200, { ok: true, set_by: by, ...(await upsertEnquiry(client(), b, new Date().toISOString(), by)) });
  } catch (err) {
    return send(res, 400, { ok: false, error: err?.message || String(err) });
  }
}

async function clientsOf(sb, rows) {
  const ids = [...new Set(rows.map((r) => r.person_id).filter(Boolean))];
  if (!ids.length) return {};
  const { data } = await sb.from('customer_person').select('person_id, display_name, email, record_type:facts->>record_type').in('person_id', ids);
  const nameOf = (id) => rows.find((r) => r.person_id === id)?.client_or_org;
  return Object.fromEntries((data || []).map((p) => [p.person_id, clientEntry(p, nameOf(p.person_id))]));
}
async function getAll(sb) {
  const [rows, config, history] = await Promise.all([
    sb.from('prospect_enquiry').select('*').order('created_at', { ascending: true }).limit(2000),
    sb.from('prospect_stage_config').select('stage, probability, label, sort').order('sort', { ascending: true }),
    sb.from('prospect_enquiry_history').select('enquiry_id, at, by, via, from_stage, to_stage, changes, matched_sale').order('at', { ascending: true }).limit(10000)
  ]);
  for (const r of [rows, config, history]) if (r.error) throw new Error(r.error.message);
  const today = new Date().toLocaleDateString('en-CA', { timeZone: 'Europe/London' });
  const pri = prioritiesOf(rows.data || [], probsOf(config.data), today);
  const list = (rows.data || []).map((r) => ({ ...r, flags: rowFlags(r, today), mail: enquiryMailLink(r.source_ref), priority: pri[r.id] || null }));
  return {
    rows: list, config: config.data || [], history: history.data || [], clients: await clientsOf(sb, list), revalidate_factor: REVALIDATE_FACTOR,
    priority_rules: PRIORITY_ASSUMPTIONS, lost_reasons: LOST_REASONS, today
  };
}

export default async function handler(req, res) {
  if (req.method === 'OPTIONS') return send(res, 204, {});
  if (!['GET', 'POST'].includes(req.method)) return send(res, 405, { ok: false, error: 'Method not allowed' });
  if (!requireAdminKeyOnly(req, res, send)) return undefined;
  try {
    if (req.method === 'GET') return send(res, 200, { ok: true, ...(await getAll(client())) });
    const b = req.body || {};
    if (b.action !== 'upsert') return send(res, 400, { ok: false, error: "action must be 'upsert'" });
    const by = setByOf(b);
    return send(res, 200, { ok: true, set_by: by, ...(await upsertEnquiry(client(), b, new Date().toISOString(), by)) });
  } catch (err) {
    const error = err?.message || String(err);
    return send(res, 400, { ok: false, error, ...explainError(error) });
  }
}
